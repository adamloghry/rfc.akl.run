#!/usr/bin/env node
/**
 * Build script: Assemble individual RFC JSON files into a single
 * JavaScript bundle for the browser.
 *
 * Usage: node scripts/build.js
 *
 * Reads: site/data/rfcs/*.json
 * Writes: site/data/rfcs-bundle.js
 */

const fs = require('fs');
const path = require('path');

const RFCS_DIR = path.join(__dirname, '..', 'site', 'data', 'rfcs');
const OUTPUT = path.join(__dirname, '..', 'site', 'data', 'rfcs-bundle.js');

// Read all JSON files
const files = fs.readdirSync(RFCS_DIR)
  .filter(f => f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  console.error('No RFC JSON files found in', RFCS_DIR);
  process.exit(1);
}

const rfcs = [];
for (const file of files) {
  const filePath = path.join(RFCS_DIR, file);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  rfcs.push(data);
}

// Sort by RFC number
rfcs.sort((a, b) => a.number - b.number);

// Generate the bundle
const bundle = `/* Auto-generated by scripts/build.js — do not edit directly */
window.RFC_DATA = ${JSON.stringify(rfcs)};
`;

fs.writeFileSync(OUTPUT, bundle);

const sizeKB = (Buffer.byteLength(bundle) / 1024).toFixed(1);
console.log(`Built ${OUTPUT}`);
console.log(`  ${rfcs.length} RFCs (${rfcs.filter(r => r.featured).length} featured, ${rfcs.filter(r => !r.featured).length} basic)`);
console.log(`  ${sizeKB} KB`);
