import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'vitest';
import { finalizeErrorPage, headersContent, redirectsContent } from '../src/integrations/build-files';
import { buildSite } from '../src/lib/model';
import { parseIndex } from '../src/lib/rfc-index';

const HERE = `${process.cwd()}/test`;
const site = buildSite({
  index: parseIndex(fs.readFileSync(path.join(HERE, 'fixtures', 'rfc-index.sample.xml'), 'utf8')),
  contentDir: path.join(HERE, 'fixtures', 'content'),
  buildDate: new Date('2026-10-15'),
});

test('_redirects has the /rfcN rule and keeps its generated header', () => {
  const r = redirectsContent(site);
  assert.match(r, /^\/rfc:num \/:num\/ 301$/m);
  assert.match(r, /^\/404 \/404\/ 301$/m);
  assert.ok(r.startsWith('# Generated by src/integrations/build-files.ts.'));
});

test('_headers sets nosniff, immutable assets and short search cache', () => {
  const h = headersContent();
  assert.match(h, /\n\/\*\n {2}X-Content-Type-Options: nosniff\n( {2}.*\n)* {2}Cache-Control: public, max-age=300\n/);
  assert.match(h, /\/assets\/\*\n {2}! Cache-Control\n {2}Cache-Control: public, max-age=31536000, immutable/);
  assert.match(h, /\/data\/search\/\*\n {2}! Cache-Control\n {2}Cache-Control: public, max-age=60/);
});

test('finalizeErrorPage moves not-found/ to 404.html and leaves the RFC 404 page alone', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'rfc-404-'));
  fs.mkdirSync(path.join(out, 'not-found'));
  fs.mkdirSync(path.join(out, '404'));
  fs.writeFileSync(path.join(out, 'not-found', 'index.html'), 'ERR');
  fs.writeFileSync(path.join(out, '404', 'index.html'), 'RFC');
  finalizeErrorPage(out);
  assert.equal(fs.readFileSync(path.join(out, '404.html'), 'utf8'), 'ERR');
  assert.equal(fs.readFileSync(path.join(out, '404', 'index.html'), 'utf8'), 'RFC');
  assert.ok(!fs.existsSync(path.join(out, 'not-found')));
});

// Full-build check: runs only when a dist/ exists (npm run build; CI builds before check-dist).
const dist = path.join(process.cwd(), 'dist');
test.skipIf(!fs.existsSync(path.join(dist, '_redirects')))('dist has both /404.html and /404/index.html', () => {
  assert.ok(fs.existsSync(path.join(dist, '404.html')));
  assert.ok(fs.existsSync(path.join(dist, '404', 'index.html')));
  assert.ok(!fs.existsSync(path.join(dist, 'not-found')));
});
